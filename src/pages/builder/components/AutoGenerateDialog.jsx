import React, { useState, useEffect } from 'react';
import { useBuilder } from '../BuilderContext';

function AutoGenerateDialog() {
  const { 
    isAutoGenerateModalOpen, setAutoGenerateModalOpen, 
    paper, sections, executeAutoGenerate, isGenerating
  } = useBuilder();

  // Local state for the configuration form, cloned from the builder sections
  const [localSections, setLocalSections] = useState([]);

  useEffect(() => {
    if (isAutoGenerateModalOpen) {
      setLocalSections(JSON.parse(JSON.stringify(sections)));
    }
  }, [isAutoGenerateModalOpen, sections]);

  if (!isAutoGenerateModalOpen) return null;

  const updateSectionConfig = (sectionIndex, field, value) => {
    const newSecs = [...localSections];
    
    if (field.includes('.')) {
      const [parent, child] = field.split('.');
      newSecs[sectionIndex].config[parent][child] = parseInt(value) || 0;
    } else {
      newSecs[sectionIndex].config[field] = value;
    }
    
    setLocalSections(newSecs);
  };

  const totalPaperMarks = localSections.reduce((sum, sec) => sum + (parseFloat(sec.total_marks) || 0), 0);

  const handleGenerate = () => {
    try {
      console.log('Generate button clicked');
      
      // Validate everything first
      for (let sec of localSections) {
        if (!sec) continue;
        const qCount = sec?.config?.internal_choice === 'Yes' ? (parseInt(sec?.config?.optional_questions) || 0) : (parseInt(sec?.config?.num_questions) || 0);
        const calculatedMarks = qCount * (parseFloat(sec?.config?.marks_per_question) || 0);
        const expectedMarks = parseFloat(sec?.total_marks) || 0;
        
        if (calculatedMarks !== expectedMarks) {
          return alert(`${sec?.name || 'Section'}: configuration (${qCount} Qs × ${sec?.config?.marks_per_question || 0} Marks = ${calculatedMarks}) does not match the required Section Marks (${expectedMarks}). Please adjust Questions or Marks/Question.`);
        }
        
        const diffSum = sec?.config?.diffDist ? Object.values(sec.config.diffDist).reduce((a,b)=>a+(parseInt(b)||0), 0) : 0;
        if (diffSum !== 100) return alert(`${sec?.name || 'Section'} Difficulty must equal 100%`);
        
        const bloomSum = sec?.config?.bloomDist ? Object.values(sec.config.bloomDist).reduce((a,b)=>a+(parseInt(b)||0), 0) : 0;
        if (bloomSum !== 100) return alert(`${sec?.name || 'Section'} Bloom's must equal 100%`);
      }
      
      console.log('Validation passed');
      executeAutoGenerate(localSections);
    } catch (err) {
      console.error('Error in handleGenerate validation:', err);
      alert('An unexpected error occurred during validation.');
    }
  };

  return (
    <div className="modal-overlay">
      <div className="modal-content" style={{width: '1100px', maxWidth:'95vw', height: '90vh', display: 'flex', flexDirection: 'column'}}>
        {/* HEADER */}
        <div className="modal-header" style={{background: 'white', borderBottom: '1px solid #e2e8f0', padding: '15px 25px'}}>
          <div style={{display:'flex', flexDirection:'column', gap:'4px'}}>
            <h3 style={{margin: 0, fontSize: '1.25rem', color: '#0f172a'}}>Auto Generate Paper</h3>
            <div style={{fontSize: '0.85rem', color: '#64748b', fontWeight:'500'}}>
              {paper?.course} • {paper?.program} | Semester {paper?.semester} • {paper?.exam_type} • 
              Target: {paper?.total_marks} Marks | <span style={{color: totalPaperMarks === paper?.total_marks ? '#16a34a' : '#ef4444', fontWeight: 'bold'}}>Configured: {totalPaperMarks} Marks</span>
            </div>
          </div>
          <div style={{display:'flex', gap:'15px', alignItems:'center'}}>
            <div style={{display:'flex', alignItems:'center', gap:'8px', fontSize:'0.85rem', fontWeight:'600', color:'#475569'}}>
              Generation Method 
              <select className="styled-input" style={{padding:'6px 12px', width:'200px'}} disabled>
                <option>Rule Based (Standard)</option>
              </select>
            </div>
            <button className="btn-icon" onClick={() => setAutoGenerateModalOpen(false)}>✕</button>
          </div>
        </div>
        
        {/* BODY */}
        <div className="modal-body" style={{flex: 1, overflowY: 'auto', background: '#f8fafc', padding: '25px'}}>
          <div style={{display: 'flex', flexDirection: 'column', gap: '25px'}}>
          {localSections.map((sec, idx) => {
            const conf = sec?.config || {};
            const diffDist = conf.diffDist || { Easy: 0, Medium: 0, Hard: 0 };
            const bloomDist = conf.bloomDist || { Remember: 0, Understand: 0, Apply: 0, Analyze: 0, Evaluate: 0, Create: 0 };
            const diffSum = (diffDist.Easy||0) + (diffDist.Medium||0) + (diffDist.Hard||0);
            const bloomSum = (bloomDist.Remember||0) + (bloomDist.Understand||0) + (bloomDist.Apply||0) + 
                             (bloomDist.Analyze||0) + (bloomDist.Evaluate||0) + (bloomDist.Create||0);
            
            return (
              <div key={sec.client_id} style={{background: 'white', borderRadius: '12px', padding: '25px', boxShadow: '0 4px 6px -1px rgba(0,0,0,0.05), 0 2px 4px -1px rgba(0,0,0,0.03)', border:'1px solid #f1f5f9'}}>
                <div style={{display:'flex', justifyContent:'space-between', alignItems:'center', borderBottom:'1px solid #e2e8f0', paddingBottom:'12px', marginBottom:'20px'}}>
                  <h4 style={{margin:0, color:'#0f172a', fontSize: '1.1rem'}}>{sec.name}</h4>
                  <span style={{fontWeight:'bold', color:'#3b82f6', background:'#eff6ff', padding:'4px 12px', borderRadius:'20px', fontSize:'0.9rem'}}>{parseFloat(sec.total_marks) || 0} Marks</span>
                </div>

                <div style={{display:'grid', gridTemplateColumns:'1fr 1fr', gap:'25px'}}>
                  <div style={{display:'flex', gap:'15px', flexDirection:'column'}}>
                    <div className="form-group">
                      <label className="form-label-small">Question Type</label>
                      <select className="styled-input" value={conf.question_type || ''} onChange={e => updateSectionConfig(idx, 'question_type', e.target.value)}>
                        <option value="Mixed">Mixed (Any)</option>
                        <option value="MCQ">MCQ Only</option>
                        <option value="Subjective">Subjective Only</option>
                      </select>
                    </div>
                    <div className="form-group">
                      <label className="form-label-small">Internal Choice</label>
                      <select className="styled-input" value={conf.internal_choice || 'No'} onChange={e => updateSectionConfig(idx, 'internal_choice', e.target.value)}>
                        <option value="No">No</option>
                        <option value="Yes">Yes (OR Questions)</option>
                      </select>
                    </div>
                    <div style={{display:'flex', gap:'15px'}}>
                      <div className="form-group">
                        <label className="form-label-small">{conf.internal_choice === 'Yes' ? 'Primary Questions' : 'Number of Questions'}</label>
                        <input type="number" className="styled-input" value={conf.internal_choice === 'Yes' ? (conf.optional_questions || 0) : (conf.num_questions || 0)} onChange={e => updateSectionConfig(idx, conf.internal_choice === 'Yes' ? 'optional_questions' : 'num_questions', e.target.value)} />
                      </div>
                      <div className="form-group">
                        <label className="form-label-small">Marks per Question</label>
                        <input type="number" step="0.5" className="styled-input" value={conf.marks_per_question || 0} onChange={e => updateSectionConfig(idx, 'marks_per_question', e.target.value)} />
                      </div>
                    </div>
                  </div>

                  <div style={{ display: 'flex', flexDirection: 'column', gap: '15px' }}>
                    <div className="form-group">
                      <label className="form-label-small">Difficulty Target (%) <span style={{fontSize:'10px', color: diffSum === 100 ? 'green' : 'red'}}>({diffSum}%)</span></label>
                      <div style={{display:'flex', gap:'10px'}}>
                        <div className="form-group"><label className="form-label-small">Easy</label><input type="number" className="styled-input" value={diffDist.Easy} onChange={e => updateSectionConfig(idx, 'diffDist.Easy', e.target.value)} /></div>
                        <div className="form-group"><label className="form-label-small">Medium</label><input type="number" className="styled-input" value={diffDist.Medium} onChange={e => updateSectionConfig(idx, 'diffDist.Medium', e.target.value)} /></div>
                        <div className="form-group"><label className="form-label-small">Hard</label><input type="number" className="styled-input" value={diffDist.Hard} onChange={e => updateSectionConfig(idx, 'diffDist.Hard', e.target.value)} /></div>
                      </div>
                    </div>
                    
                    <div className="form-group">
                      <label className="form-label-small">Bloom's Taxonomy Target (%) <span style={{fontSize:'10px', color: bloomSum === 100 ? 'green' : 'red'}}>({bloomSum}%)</span></label>
                      <div style={{display:'grid', gridTemplateColumns: 'repeat(3, 1fr)', gap:'10px'}}>
                        <div className="form-group"><label className="form-label-small">Remember</label><input type="number" className="styled-input" value={bloomDist.Remember} onChange={e => updateSectionConfig(idx, 'bloomDist.Remember', e.target.value)} /></div>
                        <div className="form-group"><label className="form-label-small">Understand</label><input type="number" className="styled-input" value={bloomDist.Understand} onChange={e => updateSectionConfig(idx, 'bloomDist.Understand', e.target.value)} /></div>
                        <div className="form-group"><label className="form-label-small">Apply</label><input type="number" className="styled-input" value={bloomDist.Apply} onChange={e => updateSectionConfig(idx, 'bloomDist.Apply', e.target.value)} /></div>
                        <div className="form-group"><label className="form-label-small">Analyze</label><input type="number" className="styled-input" value={bloomDist.Analyze} onChange={e => updateSectionConfig(idx, 'bloomDist.Analyze', e.target.value)} /></div>
                        <div className="form-group"><label className="form-label-small">Evaluate</label><input type="number" className="styled-input" value={bloomDist.Evaluate} onChange={e => updateSectionConfig(idx, 'bloomDist.Evaluate', e.target.value)} /></div>
                        <div className="form-group"><label className="form-label-small">Create</label><input type="number" className="styled-input" value={bloomDist.Create} onChange={e => updateSectionConfig(idx, 'bloomDist.Create', e.target.value)} /></div>
                      </div>
                    </div>
                  </div>
                </div>

                <div className="form-group" style={{marginTop:'20px'}}>
                  <label className="form-label">Instructions for Students (Optional)</label>
                  <textarea className="styled-input" rows="2" style={{resize:'vertical'}} value={conf.instructions || ''} onChange={e => updateSectionConfig(idx, 'instructions', e.target.value)} placeholder="Attempt any five questions."></textarea>
                </div>
              </div>
            );
          })}
          </div>
        </div>
        
        {/* STICKY FOOTER */}
        <div className="modal-footer" style={{background: 'white', padding: '15px 25px', borderTop: '1px solid #e2e8f0', display: 'flex', justifyContent: 'flex-end', gap: '15px'}}>
          <button className="btn-move" style={{padding: '10px 25px'}} onClick={() => setAutoGenerateModalOpen(false)}>Cancel</button>
          <button className="btn-save" style={{padding: '10px 30px', opacity: isGenerating ? 0.7 : 1}} onClick={handleGenerate} disabled={isGenerating}>
            {isGenerating ? '⏳ Generating...' : '✨ Generate Paper'}
          </button>
        </div>
      </div>
    </div>
  );
}

export default AutoGenerateDialog;
